func renderOp(o OpPlan) string {
	var sb strings.Builder
	sb.WriteString("runtime.Operation{")
	fmt.Fprintf(&sb, "Method: %q, Path: %q", o.Method, o.Path)
	if len(o.PathParams) > 0 {
		fmt.Fprintf(&sb, ", PathParams: %s", renderParams(o.PathParams))
	}
	if len(o.Query) > 0 {
		fmt.Fprintf(&sb, ", Query: %s", renderParams(o.Query))
	}
	if len(o.Body) > 0 {
		fmt.Fprintf(&sb, ", Body: %s", renderStrings(o.Body))
	}
	if o.IdempotencyHeader != "" {
		fmt.Fprintf(&sb, ", IdempotencyHeader: %q", o.IdempotencyHeader)
	}
	sb.WriteString("}")
	return sb.String()
}

func renderParams(ps []ParamPlan) string {
	var parts []string
	for _, p := range ps {
		s := fmt.Sprintf("{Name: %q, Attr: %q", p.Name, p.Attr)
		if p.Array {
			s += ", Array: true"
		}
		if p.Required {
			s += ", Required: true"
		}
		parts = append(parts, s+"}")
	}
	return "[]runtime.Param{" + strings.Join(parts, ", ") + "}"
}

func renderStrings(l []string) string {
	if len(l) == 0 {
		return "nil"
	}
	parts := make([]string, len(l))
	for i, s := range l {
		parts[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func renderMap(m map[string]string) string {
	if len(m) == 0 {
		return "nil"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%q: %q", k, m[k])
	}
	return "map[string]string{" + strings.Join(parts, ", ") + "}"
}
