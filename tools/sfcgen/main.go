// Command sfcgen runs the SF Compute-specific steps of `make generate`; see
// package internal/codegen for what each step does.
//
//	sfcgen prep     -in spec/openapi.json -out build/openapi.json
//	sfcgen resolve  -spec build/openapi.json -config generator_config.yml -out build/generator_config.yml -plan build/plan.json -coverage generator/coverage.txt
//	  (tfplugingen-openapi: build/generator_config.yml -> build/provider_code_spec.raw.json)
//	sfcgen patch    -in build/provider_code_spec.raw.json -plan build/plan.json -out build/provider_code_spec.json
//	  (tfplugingen-framework: build/provider_code_spec.json -> internal/generated)
//	sfcgen slim     -dir internal/generated
//	sfcgen registry -plan build/plan.json -out internal/provider/registry_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/hofvarpnir-studios/terraform-provider-sfcompute/internal/codegen"
	"github.com/hofvarpnir-studios/terraform-provider-sfcompute/internal/specmerge"
	"gopkg.in/yaml.v3"
)

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	cmd, args := os.Args[1], os.Args[2:]
	var err error
	switch cmd {
	case "prep":
		err = prep(args)
	case "resolve":
		err = resolve(args)
	case "patch":
		err = patch(args)
	case "slim":
		err = slim(args)
	case "registry":
		err = registry(args)
	default:
		usage()
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "sfcgen %s: %v\n", cmd, err)
		os.Exit(1)
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, "usage: sfcgen prep|resolve|patch|registry [flags]")
	os.Exit(2)
}

func prep(args []string) error {
	fs := flag.NewFlagSet("prep", flag.ExitOnError)
	in := fs.String("in", "spec/openapi.json", "merged OpenAPI document")
	out := fs.String("out", "build/openapi.json", "prepared OpenAPI document")
	_ = fs.Parse(args)
	data, err := os.ReadFile(*in)
	if err != nil {
		return err
	}
	doc, err := codegen.ReadJSON(data)
	if err != nil {
		return err
	}
	p, err := codegen.Prepare(doc)
	if err != nil {
		return err
	}
	for _, w := range p.Warnings {
		fmt.Fprintf(os.Stderr, "sfcgen prep: warning: %s\n", w)
	}
	return writeJSON(*out, p.Doc)
}

func resolve(args []string) error {
	fs := flag.NewFlagSet("resolve", flag.ExitOnError)
	specPath := fs.String("spec", "build/openapi.json", "prepared OpenAPI document")
	cfgPath := fs.String("config", "generator_config.yml", "generator config")
	out := fs.String("out", "build/generator_config.yml", "tfplugingen-openapi config to write")
	planPath := fs.String("plan", "build/plan.json", "resolution plan to write")
	cov := fs.String("coverage", "generator/coverage.txt", "coverage report to write")
	_ = fs.Parse(args)
	spec, err := readSpec(*specPath)
	if err != nil {
		return err
	}
	cfgData, err := os.ReadFile(*cfgPath)
	if err != nil {
		return err
	}
	cfg, err := codegen.ParseConfig(cfgData)
	if err != nil {
		return err
	}
	res, err := codegen.Resolve(spec, cfg)
	if err != nil {
		return err
	}
	for _, w := range res.Warnings {
		fmt.Fprintf(os.Stderr, "sfcgen resolve: warning: %s\n", w)
	}
	var buf bytes.Buffer
	buf.WriteString("# Generated by tools/sfcgen from generator_config.yml; DO NOT EDIT.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(res.TFGen); err != nil {
		return err
	}
	if err := writeFile(*out, buf.Bytes()); err != nil {
		return err
	}
	if err := writeJSON(*planPath, res.Plan); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "sfcgen resolve: %d resources, %d data sources\n", len(res.Plan.Resources), len(res.Plan.DataSources))
	return writeFile(*cov, []byte(res.Coverage))
}

func readPlan(path string) (*codegen.Plan, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var p codegen.Plan
	if err := json.Unmarshal(data, &p); err != nil {
		return nil, err
	}
	return &p, nil
}

func patch(args []string) error {
	fs := flag.NewFlagSet("patch", flag.ExitOnError)
	in := fs.String("in", "build/provider_code_spec.raw.json", "provider code spec from tfplugingen-openapi")
	planPath := fs.String("plan", "build/plan.json", "resolution plan")
	out := fs.String("out", "build/provider_code_spec.json", "patched provider code spec")
	_ = fs.Parse(args)
	plan, err := readPlan(*planPath)
	if err != nil {
		return err
	}
	data, err := os.ReadFile(*in)
	if err != nil {
		return err
	}
	cs, err := codegen.ReadJSON(data)
	if err != nil {
		return err
	}
	warnings, err := codegen.PatchCodeSpec(cs, plan)
	if err != nil {
		return err
	}
	for _, w := range warnings {
		fmt.Fprintf(os.Stderr, "sfcgen patch: warning: %s\n", w)
	}
	return writeJSON(*out, cs)
}

func slim(args []string) error {
	fs := flag.NewFlagSet("slim", flag.ExitOnError)
	dir := fs.String("dir", "internal/generated", "directory of tfplugingen-framework output")
	_ = fs.Parse(args)
	files, err := filepath.Glob(filepath.Join(*dir, "*", "*_gen.go"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no generated files under %s", *dir)
	}
	for _, f := range files {
		src, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		out, err := codegen.Slim(src)
		if err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		if err := os.WriteFile(f, out, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func registry(args []string) error {
	fs := flag.NewFlagSet("registry", flag.ExitOnError)
	planPath := fs.String("plan", "build/plan.json", "resolution plan")
	out := fs.String("out", "internal/provider/registry_gen.go", "registry Go file to write")
	_ = fs.Parse(args)
	plan, err := readPlan(*planPath)
	if err != nil {
		return err
	}
	const module = "github.com/hofvarpnir-studios/terraform-provider-sfcompute"
	src, err := codegen.Registry(plan, codegen.RegistryOptions{
		Package:       "provider",
		Module:        module,
		GeneratedDir:  "internal/generated",
		RuntimeImport: module + "/internal/runtime",
	})
	if err != nil {
		return err
	}
	return writeFile(*out, src)
}

func readSpec(path string) (*codegen.Spec, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	doc, err := codegen.ReadJSON(data)
	if err != nil {
		return nil, err
	}
	return &codegen.Spec{Doc: doc}, nil
}

func writeJSON(path string, v any) error {
	b, err := specmerge.Marshal(v)
	if err != nil {
		return err
	}
	return writeFile(path, b)
}

func writeFile(path string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}
